# Si lancia in Valdorso: Strumenti -> Esegui script Python -> questo file.
#
# Cosa fa:
#   1. prende "Laying Sleeping.fbx" dalla cartella Download (o da V:\Mixamo) e ne mette una copia in V:\Mixamo;
#   2. la importa sullo scheletro Mixamo che c'è già (/Game/Mixamo/StandToRoll_Skeleton, quello della capriola),
#      con l'importatore FBX classico (si spegne Interchange per un momento e poi si riaccende);
#   3. la adatta al nostro manichino con il retargeter già fatto per la capriola (/Game/Mixamo/RTG_AutoGenerated);
#   4. la chiama /Game/Mixamo/Dormire/Dorme (Content/Mixamo è fuori da GitHub, come tutto Mixamo);
#   5. scrive in Saved/Claude/dormire.txt durata, dove stanno bacino e testa e verso dove guarda il corpo sdraiato,
#      così Claude mette il corpo dritto sul materasso.
# Si può rilanciare: rifà tutto da capo.

import math
import os
import shutil
import unreal

NOME_FBX = "Laying Sleeping.fbx"
CARTELLE_FBX = [os.path.join(os.path.expanduser("~"), "Downloads"), r"V:\Mixamo"]
SCHELETRO = "/Game/Mixamo/StandToRoll_Skeleton"
MESH_MIXAMO = "/Game/Mixamo/StandToRoll"
RETARGETER = "/Game/Mixamo/RTG_AutoGenerated"
MESH_VALDORSO = "/Game/Characters/Mannequins/Meshes/SKM_Manny_Simple"
CARTELLA = "/Game/Mixamo/Dormire"
NOME_FINALE = "Dorme"
SUFFISSO = "_PerValdorso"

libreria = unreal.EditorAssetLibrary
righe = []


def scrivi(testo):
    righe.append(testo)
    unreal.log("[Valdorso] Dormire: " + testo)


def errore(testo):
    righe.append("ERRORE: " + testo)
    unreal.log_error("[Valdorso] Dormire: " + testo)


def trova_fbx():
    for cartella in CARTELLE_FBX:
        percorso = os.path.join(cartella, NOME_FBX)
        if os.path.exists(percorso):
            return percorso
    return None


def importa(fbx, scheletro):
    opzioni = unreal.FbxImportUI()
    opzioni.set_editor_property("import_mesh", False)
    opzioni.set_editor_property("import_as_skeletal", True)
    opzioni.set_editor_property("import_animations", True)
    opzioni.set_editor_property("import_materials", False)
    opzioni.set_editor_property("import_textures", False)
    opzioni.set_editor_property("skeleton", scheletro)
    opzioni.set_editor_property("mesh_type_to_import", unreal.FBXImportType.FBXIT_ANIMATION)
    compito = unreal.AssetImportTask()
    compito.filename = fbx
    compito.destination_path = CARTELLA
    compito.destination_name = "Dorme_Mixamo"
    compito.automated = True
    compito.replace_existing = True
    compito.save = True
    compito.options = opzioni
    # L'importatore nuovo (Interchange) non legge queste opzioni: per un momento si usa quello classico.
    unreal.SystemLibrary.execute_console_command(None, "Interchange.FeatureFlags.Import.FBX False")
    try:
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([compito])
    finally:
        unreal.SystemLibrary.execute_console_command(None, "Interchange.FeatureFlags.Import.FBX True")
    for percorso in libreria.list_assets(CARTELLA, recursive=True, include_folder=False):
        oggetto = libreria.load_asset(percorso)
        if isinstance(oggetto, unreal.AnimSequence):
            return oggetto
    return None


def adatta(animazione, mesh_mixamo, mesh_valdorso, retargeter):
    dati = [libreria.find_asset_data(animazione.get_path_name())]
    funzione = unreal.IKRetargetBatchOperation.duplicate_and_retarget
    tentativi = [
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA),
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA, False),
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA, False, True),
    ]
    ultimo = None
    for argomenti in tentativi:
        try:
            nuove = funzione(*argomenti)
            if nuove:
                return libreria.load_asset(str(nuove[0].package_name))
        except Exception as problema:  # noqa: BLE001
            ultimo = problema
    errore("il retarget non parte (%s). Come lo vuole il motore: %s" % (
        ultimo, (funzione.__doc__ or "").replace("\n", " | ")[:600]))
    return None


# --- Misure dell'animazione adattata (sul manichino: guarda +Y quando è in piedi) ---

CATENE = {
    "pelvis": ["root", "pelvis"],
    "thigh_l": ["root", "pelvis", "thigh_l"],
    "thigh_r": ["root", "pelvis", "thigh_r"],
    "head": ["root", "pelvis", "spine_01", "spine_02", "spine_03", "spine_04", "spine_05", "neck_01", "neck_02", "head"],
    "foot_l": ["root", "pelvis", "thigh_l", "calf_l", "foot_l"],
}


def componente(anim, nome, tempo):
    totale = unreal.Transform()
    for osso in CATENE[nome]:
        locale = unreal.AnimationLibrary.get_bone_pose_for_time(anim, osso, tempo, False)
        totale = unreal.MathLibrary.compose_transforms(locale, totale)
    return totale.translation


def misura(anim):
    durata = unreal.AnimationLibrary.get_sequence_length(anim)
    scrivi("durata %.2f s" % durata)
    for tempo in (0.0, durata * 0.5):
        bacino = componente(anim, "pelvis", tempo)
        testa = componente(anim, "head", tempo)
        piede = componente(anim, "foot_l", tempo)
        sx = componente(anim, "thigh_l", tempo)
        dx = componente(anim, "thigh_r", tempo)
        verso_testa = math.degrees(math.atan2(testa.y - bacino.y, testa.x - bacino.x))
        verso_pancia = math.degrees(math.atan2(sx.x - dx.x, -(sx.y - dx.y)))
        scrivi("a %.2f s: bacino (%.0f, %.0f, %.0f), testa (%.0f, %.0f, %.0f), piede (%.0f, %.0f, %.0f), "
               "la testa sta verso %.0f gradi dal bacino, distanza testa-piede %.0f cm, cosce verso %.0f" % (
                   tempo, bacino.x, bacino.y, bacino.z, testa.x, testa.y, testa.z, piede.x, piede.y, piede.z,
                   verso_testa, math.hypot(testa.x - piede.x, testa.y - piede.y), verso_pancia))


def principale():
    fbx = trova_fbx()
    if not fbx:
        errore("non trovo %s in Download né in V:\\Mixamo" % NOME_FBX)
        return
    copia = os.path.join(r"V:\Mixamo", NOME_FBX)
    if os.path.abspath(fbx) != os.path.abspath(copia):
        shutil.copy2(fbx, copia)
        scrivi("copia in %s" % copia)
    scheletro = libreria.load_asset(SCHELETRO)
    mesh_mixamo = libreria.load_asset(MESH_MIXAMO)
    retargeter = libreria.load_asset(RETARGETER)
    mesh_valdorso = libreria.load_asset(MESH_VALDORSO)
    if not (scheletro and mesh_mixamo and retargeter and mesh_valdorso):
        errore("manca qualcosa: scheletro %s, mesh %s, retargeter %s, manichino %s" % (
            bool(scheletro), bool(mesh_mixamo), bool(retargeter), bool(mesh_valdorso)))
        return
    if libreria.does_directory_exist(CARTELLA):
        libreria.delete_directory(CARTELLA)
    animazione = importa(fbx, scheletro)
    if animazione is None:
        errore("l'importazione non ha creato l'animazione (guardare il Registro output)")
        return
    scrivi("importata %s" % animazione.get_path_name())
    adattata = adatta(animazione, mesh_mixamo, mesh_valdorso, retargeter)
    if adattata is None:
        return
    finale = "%s/%s" % (CARTELLA, NOME_FINALE)
    if libreria.rename_asset(adattata.get_path_name().split(".")[0], finale):
        adattata = libreria.load_asset(finale)
    libreria.save_directory(CARTELLA, only_if_is_dirty=False, recursive=True)
    scrivi("adattata al manichino: %s (scheletro %s)" % (adattata.get_path_name(), adattata.get_editor_property("skeleton").get_name()))
    misura(adattata)
    cartella = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir()), "Claude")
    os.makedirs(cartella, exist_ok=True)
    with open(os.path.join(cartella, "dormire.txt"), "w", encoding="utf-8") as uscita:
        uscita.write("\n".join(righe))
    scrivi("FATTO: resoconto in Saved/Claude/dormire.txt")


try:
    principale()
finally:
    if righe:
        cartella = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir()), "Claude")
        os.makedirs(cartella, exist_ok=True)
        with open(os.path.join(cartella, "dormire.txt"), "w", encoding="utf-8") as uscita:
            uscita.write("\n".join(righe))
