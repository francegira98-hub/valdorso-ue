# Valdorso - Porta nel nostro manichino le animazioni della Free Animation Library (Fab, voxel vision, licenza Standard
# di Fab): la scala a pioli e il nuoto (e, da provare più avanti, dormire e sedersi). Scritto da Claude il 06/11/2026.
#
# Si lancia in Valdorso (Strumenti -> Esegui script Python -> questo file), con la Free Animation Library e il Sample
# Animation Pack di Epic già aggiunti al progetto (Content/FreeAnimationLibrary e Content/SampleAnimationPack).
#
# Cosa fa:
#   1. prende le animazioni scelte da /Game/FreeAnimationLibrary/Animations;
#   2. le adatta allo scheletro del nostro manichino (/Game/Characters/Mannequins/Meshes/SKM_Manny_Simple) con il
#      retargeter manichino -> manichino del Sample Animation Pack (RTG_Mannequin): gli scheletri hanno le stesse ossa,
#      cambia solo l'asset;
#   3. le mette in /Game/Fab/FreeAnimationLibrary/Movenze con nomi italiani (Scala_Su, Nuoto_Avanti, ...), senza root
#      motion (il colono lo muove il codice, l'animazione è solo aspetto) e con l'osso radice fermo;
#   4. scrive in Saved/Claude/movenze.txt quanto si sposta ogni animazione (per regolare la velocità della scala).
# Le usa UValdorsoMovenzeComponent (C++). Si può rilanciare: rifà tutto da capo. Content/Fab non va su GitHub.

import os

import unreal

ORIGINE = "/Game/FreeAnimationLibrary/Animations"
DESTINAZIONE = "/Game/Fab/FreeAnimationLibrary/Movenze"
MESH_ORIGINE = "/Game/FreeAnimationLibrary/Demo/Characters/Mannequins/Meshes/SKM_Manny_Simple"
MESH_VALDORSO = "/Game/Characters/Mannequins/Meshes/SKM_Manny_Simple"
RETARGETER = [
    "/Game/SampleAnimationPack/Demo/Characters/Mannequins/Rigs/RTG_Mannequin",
    "/Game/Mixamo/RTG_AutoGenerated",
]
SUFFISSO = "_PerValdorso"

# animazione della libreria -> nome in Valdorso
NOMI = {
    "Ladder/anim_Ladder_Up": "Scala_Su",
    "Ladder/anim_Ladder_Down": "Scala_Giu",
    "Ladder/anim_Ladder_Idle": "Scala_Ferma",
    "Swim/anim_Swim_Surface_Fwd": "Nuoto_Avanti",
    "Swim/anim_Swim_Surface_Left": "Nuoto_Sinistra",
    "Swim/anim_Swim_Surface_Right": "Nuoto_Destra",
    "Swim/anim_SwimIdle": "Nuoto_Fermo",
    # da provare più avanti (non le usa ancora nessuno): dormire e sedersi
    "Update_2/Sleep/AS_Sleep_01": "Prova_Dorme_1",
    "Update_2/Sleep/AS_Sleep_02": "Prova_Dorme_2",
    "Update_2/Sleep/AS_Sleep_03": "Prova_Dorme_3",
    "Update_2/Sleep/AS_Sleep_04": "Prova_Dorme_4",
    "Update_2/Chair/AS_Sit_01": "Prova_Siede_1",
    "Update_2/Chair/AS_Sit_02": "Prova_Siede_2",
    "Update_2/Chair/AS_Sit_03": "Prova_Siede_3",
    "Update_2/Chair/AS_Sit_04": "Prova_Siede_4",
}

libreria = unreal.EditorAssetLibrary
righe = []


def scrivi(testo):
    righe.append(testo)
    unreal.log("[Valdorso] Movenze: " + testo)


def errore(testo):
    righe.append("ERRORE: " + testo)
    unreal.log_error("[Valdorso] Movenze: " + testo)


def adatta(dati, mesh_origine, mesh_valdorso, retargeter):
    funzione = unreal.IKRetargetBatchOperation.duplicate_and_retarget
    tentativi = [
        (dati, mesh_origine, mesh_valdorso, retargeter, "", "", "", SUFFISSO, DESTINAZIONE),
        (dati, mesh_origine, mesh_valdorso, retargeter, "", "", "", SUFFISSO, DESTINAZIONE, False),
        (dati, mesh_origine, mesh_valdorso, retargeter, "", "", "", SUFFISSO, DESTINAZIONE, False, True),
    ]
    ultimo = None
    for argomenti in tentativi:
        try:
            return funzione(*argomenti)
        except Exception as problema:
            ultimo = problema
    errore("il retarget non parte (%s). Come lo vuole il motore: %s" % (
        ultimo, (funzione.__doc__ or "").replace("\n", " | ")[:900]))
    return None


def spostamento(animazione, osso):
    """Quanto si sposta un osso dall'inizio alla fine dell'animazione (cm), se si riesce a leggerlo."""
    try:
        durata = animazione.get_play_length()
        a = unreal.AnimationLibrary.get_bone_pose_for_time(animazione, osso, 0.0, False)
        b = unreal.AnimationLibrary.get_bone_pose_for_time(animazione, osso, durata, False)
        d = b.translation - a.translation
        return durata, d
    except Exception as problema:
        return None, problema


def principale():
    mesh_origine = libreria.load_asset(MESH_ORIGINE)
    mesh_valdorso = libreria.load_asset(MESH_VALDORSO)
    retargeter = None
    for percorso in RETARGETER:
        if libreria.does_asset_exist(percorso):
            retargeter = libreria.load_asset(percorso)
            scrivi("retargeter: %s" % percorso)
            break
    if not (mesh_origine and mesh_valdorso and retargeter):
        errore("manca qualcosa: manichino della libreria %s, nostro manichino %s, retargeter %s. "
               "Sono stati aggiunti al progetto la Free Animation Library e il Sample Animation Pack?" % (
                   bool(mesh_origine), bool(mesh_valdorso), bool(retargeter)))
        return

    dati = []
    per_nome = {}
    for sorgente, nome in NOMI.items():
        percorso = "%s/%s" % (ORIGINE, sorgente)
        if not libreria.does_asset_exist(percorso):
            errore("manca %s" % percorso)
            continue
        dati.append(libreria.find_asset_data(percorso))
        per_nome[sorgente.split("/")[-1]] = nome
    scrivi("trovate %d animazioni su %d" % (len(dati), len(NOMI)))
    if not dati:
        return

    if libreria.does_directory_exist(DESTINAZIONE):
        libreria.delete_directory(DESTINAZIONE)
    nuove = adatta(dati, mesh_origine, mesh_valdorso, retargeter)
    if nuove is None:
        return
    scrivi("adattate %d animazioni" % len(nuove))

    fatte = 0
    for dato in nuove:
        vecchio = str(dato.package_name)
        base = vecchio.split("/")[-1]
        originale = base[:-len(SUFFISSO)] if base.endswith(SUFFISSO) else base
        nome = per_nome.get(originale)
        if not nome:
            continue
        nuovo = "%s/%s" % (DESTINAZIONE, nome)
        if not libreria.rename_asset(vecchio, nuovo):
            errore("non riesco a rinominare %s in %s" % (vecchio, nuovo))
            continue
        animazione = libreria.load_asset(nuovo)
        if isinstance(animazione, unreal.AnimSequence):
            durata, radice = spostamento(animazione, "root")
            _, bacino = spostamento(animazione, "pelvis")
            scrivi("%s: %.2f s, radice %s, bacino %s, root motion %s" % (
                nome, durata or 0.0, radice, bacino, animazione.get_editor_property("enable_root_motion")))
            # il colono lo muove il codice: l'animazione resta sul posto
            animazione.set_editor_property("enable_root_motion", False)
            animazione.set_editor_property("force_root_lock", True)
            libreria.save_loaded_asset(animazione)
        fatte += 1
    libreria.save_directory(DESTINAZIONE, only_if_is_dirty=False, recursive=True)
    scrivi("FATTO: %d animazioni in %s. In gioco: sali una scala, nuota nel lago." % (fatte, DESTINAZIONE))


try:
    principale()
finally:
    cartella = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir()), "Claude")
    os.makedirs(cartella, exist_ok=True)
    with open(os.path.join(cartella, "movenze.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(righe) + "\n")
