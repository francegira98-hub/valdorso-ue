libreria = unreal.EditorAssetLibrary
righe = []


def scrivi(testo):
    righe.append(testo)
    unreal.log("[Valdorso] Gesti: " + testo)


def errore(testo):
    righe.append("ERRORE: " + testo)
    unreal.log_error("[Valdorso] Gesti: " + testo)


# ------------------------------------------------------------------------------------------------ 1-3. Mixamo

def importa(fbx, scheletro, nome):
    opzioni = unreal.FbxImportUI()
    opzioni.set_editor_property("import_mesh", False)
    opzioni.set_editor_property("import_as_skeletal", True)
    opzioni.set_editor_property("import_animations", True)
    opzioni.set_editor_property("import_materials", False)
    opzioni.set_editor_property("import_textures", False)
    opzioni.set_editor_property("skeleton", scheletro)
    opzioni.set_editor_property("mesh_type_to_import", unreal.FBXImportType.FBXIT_ANIMATION)
    compito = unreal.AssetImportTask()
    compito.filename = fbx
    compito.destination_path = APPOGGIO + "/" + nome
    compito.destination_name = nome + "_Mixamo"
    compito.automated = True
    compito.replace_existing = True
    compito.save = True
    compito.options = opzioni
    unreal.SystemLibrary.execute_console_command(None, "Interchange.FeatureFlags.Import.FBX False")
    try:
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([compito])
    finally:
        unreal.SystemLibrary.execute_console_command(None, "Interchange.FeatureFlags.Import.FBX True")
    for percorso in libreria.list_assets(APPOGGIO + "/" + nome, recursive=True, include_folder=False):
        oggetto = libreria.load_asset(percorso)
        if isinstance(oggetto, unreal.AnimSequence):
            return oggetto
    return None


def adatta(animazione, mesh_mixamo, mesh_valdorso, retargeter):
    dati = [libreria.find_asset_data(animazione.get_path_name())]
    funzione = unreal.IKRetargetBatchOperation.duplicate_and_retarget
    tentativi = [
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA),
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA, False),
        (dati, mesh_mixamo, mesh_valdorso, retargeter, "", "", "", SUFFISSO, CARTELLA, False, True),
    ]
    ultimo = None
    for argomenti in tentativi:
        try:
            nuove = funzione(*argomenti)
            if nuove:
                return libreria.load_asset(str(nuove[0].package_name))
        except Exception as problema:  # noqa: BLE001
            ultimo = problema
    errore("il retarget non parte (%s)" % ultimo)
    return None


def porta_mixamo():
    scheletro = libreria.load_asset(SCHELETRO)
    mesh_mixamo = libreria.load_asset(MESH_MIXAMO)
    retargeter = libreria.load_asset(RETARGETER)
    mesh_valdorso = libreria.load_asset(MESH_VALDORSO)
    if not (scheletro and mesh_mixamo and retargeter and mesh_valdorso):
        errore("manca qualcosa: scheletro %s, mesh %s, retargeter %s, manichino %s (serve la capriola di Mixamo gia' "
               "importata)" % (bool(scheletro), bool(mesh_mixamo), bool(retargeter), bool(mesh_valdorso)))
        return 0
    fatti = 0
    for inglese, italiano in NOMI.items():
        fbx = os.path.join(CARTELLA_FBX, inglese + ".fbx")
        if not os.path.exists(fbx):
            errore("non trovo %s" % fbx)
            continue
        finale = "%s/%s" % (CARTELLA, italiano)
        if libreria.does_asset_exist(finale):
            libreria.delete_asset(finale)
        originale = importa(fbx, scheletro, italiano)
        if originale is None:
            errore("%s: l'importazione non ha creato l'animazione" % inglese)
            continue
        adattata = adatta(originale, mesh_mixamo, mesh_valdorso, retargeter)
        if adattata is None:
            continue
        if libreria.rename_asset(adattata.get_path_name().split(".")[0], finale):
            adattata = libreria.load_asset(finale)
        durata = unreal.AnimationLibrary.get_sequence_length(adattata)
        scrivi("%s -> %s (%.1f s)" % (inglese, finale, durata))
        fatti += 1
    return fatti


# ------------------------------------------------------------------------------------------------ 4. i provvisori
# Le rotazioni si fanno a mano (quaternioni come tuple x, y, z, w): nello spazio del manichino (componente) la X e' il
# fianco, la Y davanti, la Z in alto. Un'alzata del braccio in avanti e' una rotazione intorno alla X: con angolo
# positivo la mano va avanti e su.
CATENA = ["root", "pelvis", "spine_01", "spine_02", "spine_03", "spine_04", "spine_05"]
BRACCIO = {"r": ["clavicle_r", "upperarm_r", "lowerarm_r"], "l": ["clavicle_l", "upperarm_l", "lowerarm_l"]}


def q_asse(asse, gradi):
    a = math.radians(gradi) / 2.0
    s = math.sin(a)
    n = math.sqrt(sum(c * c for c in asse)) or 1.0
    return (asse[0] / n * s, asse[1] / n * s, asse[2] / n * s, math.cos(a))


def q_per(a, b):
    """a * b (come FQuat: prima b, poi a)."""
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw,
            aw * bw - ax * bx - ay * by - az * bz)


def q_inv(a):
    return (-a[0], -a[1], -a[2], a[3])


def q_da(rot):
    return (rot.x, rot.y, rot.z, rot.w)


def posa(anim, osso, tempo):
    return unreal.AnimationLibrary.get_bone_pose_for_time(anim, osso, tempo, False)


def onda(fase, salita, colpo):
    """Martellare: da 0 a 1 piano (fino a salita), da 1 a 0 di colpo (fino a colpo), poi fermo a 0."""
    if fase < salita:
        u = fase / salita
        return 0.5 - 0.5 * math.cos(math.pi * u)
    if fase < colpo:
        u = (fase - salita) / (colpo - salita)
        return 1.0 - u * u
    return 0.0


def posa_martellare(fase):
    """Gradi (spalla avanti, gomito, schiena avanti) per il braccio destro, e per il sinistro (tiene il ferro)."""
    su = onda(fase, 0.62, 0.78)
    destro = (35.0 + 85.0 * su, 40.0 + 55.0 * su, -2.0 - 6.0 * (1.0 - su))
    sinistro = (38.0, 55.0)
    return destro, sinistro, destro[2]


def posa_spazzare(fase):
    """Il manico della scopa: braccia avanti e giu', la schiena che gira da una parte all'altra."""
    giro = math.sin(2.0 * math.pi * fase) * 16.0
    destro = (28.0 + 6.0 * math.sin(2.0 * math.pi * fase), 30.0)
    sinistro = (48.0 - 6.0 * math.sin(2.0 * math.pi * fase), 25.0)
    return destro, sinistro, -10.0, giro


def scrivi_chiavi(controllo, anim, osso, chiavi):
    """Le chiavi (posizioni, rotazioni, scale) di un osso: prova i tipi che il motore vuole (5.x: Vector3f/Quat4f)."""
    pos, rot, sca = chiavi

    def nuovo(tipo, valori, nomi):
        """(11/11) Vector3f e Quat4f in Python non prendono i numeri nel costruttore: si fanno vuoti e si riempiono."""
        try:
            return tipo(*valori)
        except Exception:  # noqa: BLE001
            o = tipo()
            for nome, v in zip(nomi, valori):
                try:
                    setattr(o, nome, float(v))
                except Exception:  # noqa: BLE001
                    o.set_editor_property(nome, float(v))
            return o

    def tipi_float():
        return ([nuovo(unreal.Vector3f, (p.x, p.y, p.z), "xyz") for p in pos],
                [nuovo(unreal.Quat4f, r, "xyzw") for r in rot],
                [nuovo(unreal.Vector3f, (v.x, v.y, v.z), "xyz") for v in sca])

    def tipi_double():
        return (list(pos), [unreal.Quat(r[0], r[1], r[2], r[3]) for r in rot], list(sca))

    prove = []
    if hasattr(unreal, "Vector3f") and hasattr(unreal, "Quat4f"):
        prove.append(tipi_float)
    prove.append(tipi_double)
    ultimo = None
    for fai in prove:
        try:
            p, r, s = fai()
            if controllo.set_bone_track_keys(unreal.Name(osso), p, r, s):
                return True
        except Exception as problema:  # noqa: BLE001
            ultimo = problema
    errore("%s: le chiavi non entrano (%s)" % (osso, ultimo))
    return False


def provvisorio(nome, ciclo, funzione):
    finale = "%s/%s" % (CARTELLA, nome)
    if libreria.does_asset_exist(finale):
        libreria.delete_asset(finale)
    copia = libreria.duplicate_asset(RIPOSO, finale)
    if copia is None:
        errore("%s: non riesco a copiare %s" % (nome, RIPOSO))
        return False
    durata = unreal.AnimationLibrary.get_sequence_length(copia)
    chiavi = unreal.AnimationLibrary.get_num_keys(copia)
    if chiavi < 2 or durata <= 0.0:
        errore("%s: la copia del respiro e' vuota" % nome)
        return False
    giri = max(1, int(round(durata / ciclo)))
    controllo = None
    for prova in (lambda: copia.controller, lambda: copia.get_editor_property("controller"), lambda: copia.get_controller()):
        try:
            controllo = prova()
            if controllo:
                break
        except Exception:  # noqa: BLE001
            controllo = None
    if controllo is None:
        errore("%s: non trovo il controllo dei dati dell'animazione (AnimationDataController)" % nome)
        return False
    ossa_mosse = ["spine_03", "upperarm_r", "lowerarm_r", "upperarm_l", "lowerarm_l"]
    nuove = {o: ([], [], []) for o in ossa_mosse}
    asse_fianco = (1.0, 0.0, 0.0)
    asse_su = (0.0, 0.0, 1.0)
    for k in range(chiavi):
        t = durata * k / (chiavi - 1)
        fase = (t * giri / durata) % 1.0
        locali = {}
        for osso in CATENA + BRACCIO["r"] + BRACCIO["l"]:
            locali[osso] = posa(copia, osso, t)
        # le rotazioni nello spazio del manichino, lungo la catena
        comp = {}
        padre = (0.0, 0.0, 0.0, 1.0)
        for osso in CATENA:
            padre = q_per(padre, q_da(locali[osso].rotation))
            comp[osso] = padre
        valori = funzione(fase)
        destro, sinistro, schiena = valori[0], valori[1], valori[2]
        giro = valori[3] if len(valori) > 3 else 0.0
        # la schiena (spine_03): un poco avanti, e (per la scopa) girata
        d_schiena = q_per(q_asse(asse_su, giro), q_asse(asse_fianco, schiena))
        padre3 = comp["spine_02"]
        nuova3 = q_per(d_schiena, comp["spine_03"])
        locale3 = q_per(q_inv(padre3), nuova3)
        nuove["spine_03"][0].append(locali["spine_03"].translation)
        nuove["spine_03"][1].append(locale3)
        nuove["spine_03"][2].append(locali["spine_03"].scale3d)
        # dopo spine_03 la catena e' girata con lei
        giu = nuova3
        for osso in ("spine_04", "spine_05"):
            giu = q_per(giu, q_da(locali[osso].rotation))
        for lato, (spalla, gomito) in (("r", destro[:2]), ("l", sinistro[:2])):
            clav, sup, inf = BRACCIO[lato]
            c_clav = q_per(giu, q_da(locali[clav].rotation))
            c_sup = q_per(c_clav, q_da(locali[sup].rotation))
            c_inf = q_per(c_sup, q_da(locali[inf].rotation))
            d1 = q_asse(asse_fianco, spalla)
            n_sup = q_per(d1, c_sup)
            n_inf = q_per(q_asse(asse_fianco, gomito), q_per(d1, c_inf))
            nuove[sup][0].append(locali[sup].translation)
            nuove[sup][1].append(q_per(q_inv(c_clav), n_sup))
            nuove[sup][2].append(locali[sup].scale3d)
            nuove[inf][0].append(locali[inf].translation)
            nuove[inf][1].append(q_per(q_inv(n_sup), n_inf))
            nuove[inf][2].append(locali[inf].scale3d)
    try:
        controllo.open_bracket(unreal.Text("Valdorso: " + nome), False)
    except Exception:  # noqa: BLE001
        pass
    buoni = 0
    for osso in ossa_mosse:
        if scrivi_chiavi(controllo, copia, osso, nuove[osso]):
            buoni += 1
    try:
        controllo.close_bracket(False)
    except Exception:  # noqa: BLE001
        pass
    libreria.save_asset(finale, only_if_is_dirty=False)
    scrivi("%s: %d ossa mosse su %d, %.1f s, %d giri (provvisorio)" % (nome, buoni, len(ossa_mosse), durata, giri))
    return buoni == len(ossa_mosse)


def principale():
    fatti = porta_mixamo()
    scrivi("Mixamo: %d gesti su %d" % (fatti, len(NOMI)))
    for nome, ciclo, funzione in (("Martellare", 1.15, posa_martellare), ("Spazzare", 1.6, posa_spazzare)):
        try:
            provvisorio(nome, ciclo, funzione)
        except Exception as problema:  # noqa: BLE001
            errore("%s: %s" % (nome, problema))
    libreria.save_directory(CARTELLA, only_if_is_dirty=False, recursive=True)
    scrivi("FATTO: i gesti sono in %s (resoconto in Saved/Claude/gesti.txt)" % CARTELLA)


try:
    principale()
finally:
    cartella = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir()), "Claude")
    os.makedirs(cartella, exist_ok=True)
    with open(os.path.join(cartella, "gesti.txt"), "w", encoding="utf-8") as uscita:
        uscita.write("\n".join(righe))
